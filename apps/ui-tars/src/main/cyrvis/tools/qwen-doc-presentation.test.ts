import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  configureQwenDocPresentation,
  createQwenDocPresentation,
} from './qwen-doc-presentation';

const presentationBytes = Buffer.from([
  0x50, 0x4b, 0x03, 0x04, 0x14, 0x00, 0x00, 0x00,
]);

const successfulGenerationResponse = (
  downloadUrl = 'https://files.example.com/deck.pptx',
) => {
  const encoder = new TextEncoder();
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      controller.enqueue(
        encoder.encode(
          `data: ${JSON.stringify({
            choices: [{ delta: { content: downloadUrl } }],
          })}\n\n`,
        ),
      );
      controller.enqueue(encoder.encode('data: [DONE]\n\n'));
      controller.close();
    },
  });
  return new Response(stream, {
    status: 200,
    headers: { 'content-type': 'text/event-stream' },
  });
};

describe('createQwenDocPresentation API key fallback', () => {
  let root: string;

  beforeEach(async () => {
    root = await fs.mkdtemp(path.join(os.tmpdir(), 'cyrvis-qwen-doc-'));
    configureQwenDocPresentation({});
    vi.stubEnv('CYRVIS_QWEN_DOC_API_KEY', 'dedicated-key');
    vi.stubEnv('DASHSCOPE_API_KEY', 'dashscope-key');
    vi.stubEnv('QWEN_API_KEY', 'generic-qwen-key');
    vi.stubEnv('CYRVIS_QWEN_DOC_BASE_URL', '');
    vi.stubEnv('CYRVIS_QWEN_DOC_WORKSPACE_ID', '');
    vi.stubEnv('QWEN_WORKSPACE_ID', '');
  });

  afterEach(async () => {
    vi.unstubAllEnvs();
    vi.unstubAllGlobals();
    configureQwenDocPresentation({});
    await fs.rm(root, { recursive: true, force: true });
  });

  it('tries QWEN_API_KEY after dedicated keys are rejected', async () => {
    const authorizationHeaders: string[] = [];
    const fetchMock = vi.fn(
      async (input: string | URL | Request, init?: RequestInit) => {
        const url = new URL(
          typeof input === 'string'
            ? input
            : input instanceof URL
              ? input.toString()
              : input.url,
        );
        if (url.pathname.endsWith('/chat/completions')) {
          authorizationHeaders.push(
            new Headers(init?.headers).get('authorization') || '',
          );
          if (authorizationHeaders.length === 1) {
            return new Response('{"message":"invalid API key"}', {
              status: 401,
              statusText: 'Unauthorized',
            });
          }
          if (authorizationHeaders.length === 2) {
            return new Response('{"message":"quota exceeded"}', {
              status: 429,
              statusText: 'Too Many Requests',
            });
          }
          return successfulGenerationResponse();
        }
        return new Response(presentationBytes, {
          status: 200,
          headers: {
            'content-type':
              'application/vnd.openxmlformats-officedocument.presentationml.presentation',
            'content-length': String(presentationBytes.length),
          },
        });
      },
    );
    vi.stubGlobal('fetch', fetchMock);

    const target = path.join(root, 'fallback.pptx');
    const result = await createQwenDocPresentation({
      path: target,
      title: 'Fallback deck',
      content: 'A detailed presentation generated by the fallback key.',
      pageCount: 8,
    });

    expect(authorizationHeaders).toEqual([
      'Bearer dedicated-key',
      'Bearer dashscope-key',
      'Bearer generic-qwen-key',
    ]);
    expect(result).toMatchObject({
      provider: 'qwen-doc-turbo',
      model: 'qwen-doc-turbo',
      bytes: presentationBytes.length,
    });
    await expect(fs.readFile(target)).resolves.toEqual(presentationBytes);
  });

  it('upgrades trusted Qwen HTTP download links to HTTPS', async () => {
    vi.stubEnv('CYRVIS_QWEN_DOC_API_KEY', '');
    vi.stubEnv('DASHSCOPE_API_KEY', '');
    const downloadedUrls: string[] = [];
    const fetchMock = vi.fn(
      async (input: string | URL | Request, _init?: RequestInit) => {
        const url = new URL(
          typeof input === 'string'
            ? input
            : input instanceof URL
              ? input.toString()
              : input.url,
        );
        if (url.pathname.endsWith('/chat/completions')) {
          return successfulGenerationResponse(
            // secretlint-disable-next-line @secretlint/secretlint-rule-pattern
            'http://dashscope-file.oss-cn-beijing.aliyuncs.com/deck.pptx?token=test',
          );
        }
        downloadedUrls.push(url.toString());
        return new Response(presentationBytes, {
          status: 200,
          headers: {
            'content-type':
              'application/vnd.openxmlformats-officedocument.presentationml.presentation',
            'content-length': String(presentationBytes.length),
          },
        });
      },
    );
    vi.stubGlobal('fetch', fetchMock);

    await createQwenDocPresentation({
      path: path.join(root, 'trusted-download.pptx'),
      title: 'Trusted download',
      content: 'A presentation with a trusted temporary download link.',
      pageCount: 8,
    });

    expect(downloadedUrls).toEqual([
      // secretlint-disable-next-line @secretlint/secretlint-rule-pattern
      'https://dashscope-file.oss-cn-beijing.aliyuncs.com/deck.pptx?token=test',
    ]);
  });
});
